export type Inventory = {
  skills: string[];
  prompts: string[];
  extensions: string[];
  clis: string[];
};

/** CLIs worth reporting presence of — variable across machines and not printed
 * anywhere else, unlike skills/prompts which Pi lists at startup. Kept to
 * widely-used developer tools; override with PI_KING_CLIS (comma-separated) to
 * track your own. Listing someone's private tooling by default would leak the
 * shape of their setup into any screenshot they share. */
const CLI_CANDIDATES = process.env.PI_KING_CLIS?.trim()
  ? process.env.PI_KING_CLIS.split(",").map((c) => c.trim()).filter(Boolean)
  : ["bat", "docker", "fd", "gh", "jq", "rg", "tmux"];

function listDir(path: string, pick: (entry: string, full: string) => string | undefined): string[] {
  try {
    return readdirSync(path)
      .map((e) => pick(e, join(path, e)))
      .filter((v): v is string => Boolean(v))
      .sort()
      .map((n) => clean(n, 80));
  } catch {
    return [];
  }
}

function onPath(cmd: string): boolean {
  const dirs = (process.env.PATH ?? "").split(":").filter(Boolean);
  for (const d of dirs) {
    try {
      statSync(join(d, cmd));
      return true;
    } catch {
      // not here; keep looking
    }
  }
  return false;
}

/**
 * Snapshot of what's installed. Called once when the dashboard opens — this is
 * static between config edits, so there is no refresh and no TTL.
 * Measured at ~0.1s in Python, dominated by interpreter startup; here it is a
 * handful of readdir/stat calls.
 */
/** Strips terminal control sequences from a string that came from outside this
 * process: a directory name, a session name, a field in someone else's status
 * file. Directory names may legally contain ESC on macOS and Linux, and nothing
 * validates the contents of a status file, so rendering these raw lets an
 * unrelated string reposition the cursor, repaint the screen, or forge a row
 * that looks like a different session. Also applied before send-keys, where a
 * newline would submit a line and leave the remainder as a prompt typed into a
 * running agent. */
export function clean(value: string, max = 200): string {
  // eslint-disable-next-line no-control-regex
  return value.replace(/[\u0000-\u001f\u007f-\u009f]/g, "").slice(0, max);
}

export function readInventory(): Inventory {
  return {
    skills: listDir(join(AGENT_DIR, "skills"), (e, full) => {
      try {
        statSync(join(full, "SKILL.md"));
        return e;
      } catch {
        return undefined;
      }
    }),
    prompts: listDir(join(AGENT_DIR, "prompts"), (e) => (e.endsWith(".md") ? e.replace(/\.md$/, "") : undefined)),
    extensions: listDir(join(AGENT_DIR, "extensions"), (e) => (e.endsWith(".ts") ? e.replace(/\.ts$/, "") : undefined)),
    clis: CLI_CANDIDATES.filter(onPath),
  };
}

