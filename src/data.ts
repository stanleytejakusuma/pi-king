export type LifetimeStats = {
  tokensIn: number;
  tokensOut: number;
  /** Cache reads, so callers can subtract them. Input alone counts the same
   * history re-sent each turn as though it were new text. */
  tokensCacheRead: number;
  /** Cache writes. Read over write is the leverage of caching: how many times
   * each token written into the cache was served back out of it. */
  tokensCacheWrite: number;
  /** Reasoning tokens, reported beside output and never derived from it —
   * measured not to be a strict subset of `out`. */
  tokensReasoning: number;
  calls: number;
  activeDays: number;
  currentStreak: number;
  longestStreak: number;
  days: DayTotal[];
};

export type DayTotal = {
  day: string; tokensIn: number; tokensOut: number; tokensCacheRead: number;
  // Added after the cache first shipped. The cache requires every field to be
  // present before it trusts an entry, so entries written before these existed
  // are recomputed on the next scan rather than read back as zero.
  tokensCacheWrite: number; tokensReasoning: number;
  calls: number;
};

export type RecentProject = { project: string; path: string; lastActive: number };

/** The last assistant text from a session transcript, read from the tail
 * without slurping the file (transcripts reach multi-MB). This is what Claude
 * Code's agent list shows per agent, and it is the best answer to "what did
 * this session last say" that exists on disk — it works for sessions running
 * older extension code and for exited cards, because the transcript is the
 * source, not the tracker. Assistant entries whose content is only thinking
 * blocks are skipped; the reply is the thing said out loud. */
export function readLastReply(sessionFile: string, tailBytes = 262_144): string | undefined {
  let fd: number | undefined;
  try {
    fd = openSync(sessionFile, "r");
    const size = fstatSync(fd).size;
    const start = Math.max(0, size - tailBytes);
    const buf = Buffer.alloc(Math.min(tailBytes, size));
    readSync(fd, buf, 0, buf.length, start);
    const lines = buf.toString("utf8").split("\n");
    // First line may be a partial JSON record when the window starts mid-line;
    // JSON.parse simply rejects it, which is the correct outcome.
    for (let i = lines.length - 1; i >= 0; i--) {
      let entry: { type?: string; message?: { role?: string; content?: unknown } };
      try { entry = JSON.parse(lines[i]); } catch { continue; }
      if (entry.type !== "message" || entry.message?.role !== "assistant") continue;
      const content = Array.isArray(entry.message.content) ? entry.message.content : [];
      for (const c of content) {
        const block = c as { type?: string; text?: string };
        if (block?.type === "text" && typeof block.text === "string") {
          // Markdown emphasis markers are noise at one line of display width;
          // stripping them is display formatting, not content editing.
          const text = clean(block.text.replace(/[*`_#]/g, "").replace(/\s+/g, " ").trim());
          if (text) return text.length > 200 ? `${text.slice(0, 199)}\u2026` : text;
        }
      }
    }
    return undefined;
  } catch {
    return undefined;
  } finally {
    if (fd !== undefined) try { closeSync(fd); } catch { /* already closed */ }
  }
}

/** Reads just the first line of a file without slurping it. Session
 * transcripts reach multi-MB; only the opening `session` entry is needed. */
function firstLine(path: string, max = 512): string {
  let fd: number | undefined;
  try {
    fd = openSync(path, "r");
    const buf = Buffer.alloc(max);
    const n = readSync(fd, buf, 0, max, 0);
    const text = buf.subarray(0, n).toString("utf8");
    const nl = text.indexOf("\n");
    return nl === -1 ? text : text.slice(0, nl);
  } catch {
    return "";
  } finally {
    if (fd !== undefined) {
      try { closeSync(fd); } catch { /* already gone */ }
    }
  }
}

/**
 * Recent project directories, newest first, for the landing page when no
 * sessions are running — so an empty dashboard offers a way back into work
 * instead of just saying "nothing here".
 *
 * The real cwd is read from the opening `session` entry of the newest
 * transcript, NOT decoded from the session directory name. That encoding
 * (`--Users-you-codebase-example-project--`) is genuinely ambiguous: a literal
 * hyphen in a directory name is indistinguishable from a path separator, so
 * naive decoding turns `codebase/example-project` into `codebase/example/project`.
 * Confirmed against a real session before choosing this approach.
 *
 * Cost stays low: one readdir per project dir plus a 512-byte read of one
 * file. Transcripts are never parsed.
 */
export function readRecentProjects(limit: number): RecentProject[] {
  const root = join(AGENT_DIR, "sessions");
  let entries: string[];
  try {
    entries = readdirSync(root);
  } catch {
    return [];
  }

  const dirs: Array<{ dir: string; lastActive: number }> = [];
  for (const e of entries) {
    try {
      const st = statSync(join(root, e));
      if (st.isDirectory()) dirs.push({ dir: e, lastActive: st.mtimeMs });
    } catch {
      // vanished between readdir and stat; skip
    }
  }
  dirs.sort((a, b) => b.lastActive - a.lastActive);

  const out: RecentProject[] = [];
  for (const { dir, lastActive } of dirs) {
    if (out.length >= limit) break;
    const full = join(root, dir);
    let newest: { file: string; mtime: number } | undefined;
    try {
      for (const f of readdirSync(full)) {
        if (!f.endsWith(".jsonl")) continue;
        const mt = statSync(join(full, f)).mtimeMs;
        if (!newest || mt > newest.mtime) newest = { file: f, mtime: mt };
      }
    } catch {
      continue;
    }
    if (!newest) continue;
    let cwd = "";
    try {
      const parsed = JSON.parse(firstLine(join(full, newest.file))) as { cwd?: unknown };
      if (typeof parsed.cwd === "string") cwd = parsed.cwd;
    } catch {
      // Unparseable opening entry — skip rather than show a guessed path.
      continue;
    }
    if (!cwd) continue;
    out.push({ project: clean(basename(cwd) || cwd, 60), path: clean(cwd, 200), lastActive });
  }
  return out;
}

/** Unicode block sparkline. Returns "" for empty input rather than a fake flat
 * line, so "no data" never renders as "measured zero".
 *
 * Exactly zero renders as a gap, not as the shortest bar. The block set starts
 * at the one-eighth block, so without this a day with no activity and a day
 * with a trace of it drew the same mark. That is harmless for volume and wrong
 * beside the streak counters, where the day that renders as a small bar is
 * precisely the day that ended a streak. A gap says nothing happened; the
 * shortest bar says something did. */
export function sparkline(series: number[]): string {
  if (series.length === 0) return "";
  const blocks = "\u2581\u2582\u2583\u2584\u2585\u2586\u2587\u2588";
  const max = Math.max(...series);
  if (max <= 0) return "";
  return series.map((v) => (v <= 0 ? " " : blocks[Math.min(7, Math.floor((v / max) * 7))])).join("");
}

