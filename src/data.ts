/**
 * data.ts — data sources for the pi-king dashboard banner,
 * stats line, inventory block, and landing page.
 *
 * Kept separate from pi-dashboard.ts so the rendering code stays readable and
 * so each source's cost and failure mode is documented next to the code that
 * pays it. Every source here is local-only: no network, no daemon, no auth.
 *
 * Deliberately NOT sourced here:
 *  - Skill/prompt invocation counts. Pi's session JSONL format records no
 *    skill-invocation entry (verified against all 101 session files: entry
 *    types are only message / custom / model_change / session / session_info /
 *    thinking_level_change, and skills expand inline into user message text
 *    leaving no structured marker). Deriving counts would mean fuzzy string
 *    matching across multi-MB transcripts — unreliable and slow. Inventory is
 *    therefore sorted alphabetically, not by usage.
 *  - Cost. call_logs carries no price data; a hardcoded price table would rot
 *    silently. A fabricated authoritative-looking number is worse than none.
 */

