export type UsageStats = {
  /** Token totals for the day. cacheRead is broken out because it is the number
   * that actually predicts spend: cached input is billed at a fraction of fresh
   * input, so a high cache share means a large token count is cheap. */
  tokensIn: number;
  tokensOut: number;
  tokensCacheRead: number;
  /** Busiest part of the day by call count, in local time, with its share.
   * Undefined when there are too few calls for the answer to mean anything. */
  peakPeriod?: { label: string; pct: number };
  /** Request durations in ms, sorted, for percentile reporting. The mean hides
   * the tail, and the tail is what a person waiting on a session notices. */
  durations: number[];
  calls: number;
  errors: number;
  topModels: Array<{ model: string; pct: number }>;
  /** Per-model figures for the stats screen, sorted by call count. p95 is per
   * model because a slow tail usually belongs to one model, and the aggregate
   * p95 hides which. */
  perModel: Array<{ model: string; calls: number; tokensIn: number; errors: number; p95: number }>;
  /** HTTP status codes >= 400 with their counts, most frequent first. The
   * band's error rate says how much is failing; this says what kind. */
  errorsByStatus: Array<[number, number]>;
  /** The single longest call. p95 hides the outlier that made someone wait. */
  slowest: { duration: number; model: string } | undefined;
  /** Tokens written into the provider cache. Read over write is the leverage
   * of caching: how many times each cached token was served back. */
  tokensCacheWrite: number;
  /** Reasoning tokens. Measured NOT to be a strict subset of `out` (7 of
   * 9,058 sampled records exceed it), so it is reported beside output, never
   * derived from it. */
  tokensReasoning: number;
  /** Calls per hour, midnight through the current hour. Real data from each
   * call's own timestamp — not smoothed, not synthesised. */
  hourly: number[];
  peakHour: number;
  partial: boolean;
  /** Activity in the trailing 60 minutes: the band's other numbers are
   * day-cumulative, which reads the same at a busy noon and a dead midnight.
   * Window is clipped to today's log directory, so just after midnight it may
   * miss calls from late yesterday — clipped, never padded. */
  lastHour: { calls: number; tokensIn: number };
};

function today(): string {
  return localDateOf(new Date());
}

/** A record's LOCAL calendar date, computed from its own timestamp.
 *
 * Never trust a call-log directory's name for this. The router names
 * directories by UTC calendar day, and a human's "day" is a LOCAL calendar
 * day — the two boundaries disagree by the local UTC offset for anyone not on
 * UTC. Verified at UTC+7: a call made 7 minutes before this fix was written
 * sat in the PREVIOUS UTC day's directory while being unambiguously part of
 * local "today" by any human definition. For that machine, every single day
 * has a 7-hour window (local midnight to 7am) where "today's" UTC-named
 * directory does not exist yet, and the band would report no activity
 * despite calls having already happened. Accepts a Date or a parseable
 * timestamp string; getFullYear/getMonth/getDate are LOCAL accessors. */
function localDateOf(input: Date | string): string {
  const t = typeof input === "string" ? new Date(input) : input;
  const p = (n: number) => String(n).padStart(2, "0");
  return `${t.getFullYear()}-${p(t.getMonth() + 1)}-${p(t.getDate())}`;
}

/** Strips vendor/route prefixes so model names fit the one-line ticker. */
function shortModel(id: string): string {
  return id.replace(/^omni-/, "").replace(/^(anthropic|openai|codex|claude)\//, "");
}

/**
 * Aggregates today's call logs from the directory named by PI_KING_CALL_LOGS.
 *
 * Cost is real: ~2,100 files for a busy day, measured at ~0.5s. That is far
 * too slow for the dashboard's 1s render tick, so this is async and callers
 * must cache it (see StatsCache) rather than awaiting it on the render path.
 *
 * Returns undefined when no log directory is configured, or when today's
 * directory does not exist — meaning no calls were routed today. Callers must
 * render nothing rather than "0 calls", which would falsely imply measured
 * inactivity rather than absent measurement.
 */
/** Per-day input-token totals, oldest first, for the daily sparkline.
 *
 * A mean is not offered deliberately. Measured usage spans a 70x range across
 * eight days, so a single average collapses "barely touched it" and "ran it all
 * week" into one number that describes neither. A sparkline shows the burst
 * instead of hiding it, and the eye does the comparison without arithmetic.
 *
 * Caching: a closed UTC directory's logs never change, so its contribution is
 * computed once and kept. The two most recent UTC directories are always
 * rescanned, because the router can still write into either. "Day" here is
 * always a LOCAL calendar date, never the UTC directory name — the router
 * names directories by UTC calendar day, which disagrees with a human's day
 * by the local UTC offset, so a single directory routinely splits across two
 * local dates (verified: at UTC+7, every UTC directory's last 7 hours belong
 * to the NEXT local date). Bucketing is per record, by that record's own
 * timestamp, never by which directory it happens to sit in — see localDateOf.
 */
/** When the caller has already scanned today's directory (readUsageStats
 * does, for the band), it passes the result here so today is not read twice
 * per refresh. Both scans count identically — same files, same summary
 * fields — so substituting one for the other cannot change a number. */
type DayFields = Omit<DayTotal, "day">;
/** Cached per UTC DIRECTORY, not per local day — the unit that is actually
 * closed-and-immutable is the directory (the router will never write into it
 * again once a newer one appears), and one directory's records can split
 * across two local dates for anyone not on UTC. Usually a small map (one
 * entry, or two when the directory straddles a local-day boundary). */
type DirCacheEntry = Record<string, DayFields>;

const ZERO_FIELDS = (): DayFields => ({ tokensIn: 0, tokensOut: 0, tokensCacheRead: 0, tokensCacheWrite: 0, tokensReasoning: 0, calls: 0 });
const FIELD_NAMES = ["tokensIn", "tokensOut", "tokensCacheRead", "tokensCacheWrite", "tokensReasoning", "calls"] as const;
const isComplete = (h: Record<string, unknown> | undefined): h is DayFields =>
  !!h && FIELD_NAMES.every((f) => typeof h[f] === "number");
function addFields(into: Map<string, DayFields>, localDay: string, e: DayFields): void {
  const cur = into.get(localDay) ?? ZERO_FIELDS();
  cur.tokensIn += e.tokensIn; cur.tokensOut += e.tokensOut; cur.tokensCacheRead += e.tokensCacheRead;
  cur.tokensCacheWrite += e.tokensCacheWrite; cur.tokensReasoning += e.tokensReasoning; cur.calls += e.calls;
  into.set(localDay, cur);
}

export async function readDailyTokens(todayOverride?: DayTotal): Promise<DayTotal[]> {
  if (!CALL_LOGS) return [];
  let dirs: string[];
  try {
    dirs = (await readdir(CALL_LOGS)).filter((d) => /^\d{4}-\d{2}-\d{2}$/.test(d)).sort();
  } catch {
    return [];
  }
  // Only the last two UTC-named directories can still receive new writes —
  // the router starts a fresh one at UTC midnight and never revisits an old
  // one — so "volatile" here means exactly "not yet closed", same test as
  // before. It is NOT trying to guess which directories feed local-today;
  // per-record bucketing below makes that unnecessary. A directory is safe to
  // cache once it is closed, full stop, regardless of which local date(s) its
  // records land in.
  const volatile = new Set(dirs.slice(-2));

  let cache: Record<string, DirCacheEntry> = {};
  try {
    cache = JSON.parse(readFileSync(DAILY_CACHE, "utf8")) as typeof cache;
  } catch { /* first run, or unreadable: rebuild */ }

  const merged = new Map<string, DayFields>();
  const scanned = new Set(dirs);
  let dirty = false;

  for (const dir of dirs) {
    const cached = cache[dir];
    if (!volatile.has(dir) && cached && Object.values(cached).every(isComplete)) {
      for (const [localDay, fields] of Object.entries(cached)) addFields(merged, localDay, fields);
      continue;
    }
    const byLocal: DirCacheEntry = {};
    try {
      const files = (await readdir(join(CALL_LOGS, dir))).filter((f) => f.endsWith(".json"));
      const BATCH = 64;
      for (let i = 0; i < files.length; i += BATCH) {
        const parsed = await Promise.all(files.slice(i, i + BATCH).map(async (f) => {
          try {
            return JSON.parse(await readFile(join(CALL_LOGS, dir, f), "utf8")) as { summary?: Record<string, unknown> };
          } catch {
            return undefined;
          }
        }));
        for (const r of parsed) {
          if (!r?.summary) continue;
          // The directory name is only a fallback for the rare record whose own
          // timestamp cannot be parsed — never the primary source of its day.
          const localDay = typeof r.summary.timestamp === "string" && r.summary.timestamp.length >= 10
            ? localDateOf(r.summary.timestamp) : dir;
          const e = byLocal[localDay] ?? ZERO_FIELDS();
          e.calls++;
          const tk = r.summary.tokens as Record<string, unknown> | undefined;
          if (tk) {
            e.tokensIn += Number(tk.in) || 0;
            e.tokensOut += Number(tk.out) || 0;
            e.tokensCacheRead += Number(tk.cacheRead) || 0;
            e.tokensCacheWrite += Number(tk.cacheWrite) || 0;
            e.tokensReasoning += Number(tk.reasoning) || 0;
          }
          byLocal[localDay] = e;
        }
      }
    } catch { continue; }
    for (const [localDay, fields] of Object.entries(byLocal)) addFields(merged, localDay, fields);
    if (!volatile.has(dir)) { cache[dir] = byLocal; dirty = true; }
  }

  // Lifetime means lifetime: the router rotates old log directories away, and
  // deriving the series purely from surviving directories made every figure
  // labelled "lifetime" quietly shrink as days rotated out. A cached directory
  // was measured while its logs existed, so it still contributes after they
  // are gone — but only if every one of its local-date entries is complete,
  // because a gone directory can never be rescanned to fill in a missing
  // field. Incomplete orphans stay in the cache file (they are measurements;
  // deleting them destroys data) and out of the series.
  for (const [dirName, entry] of Object.entries(cache)) {
    if (scanned.has(dirName)) continue; // already merged above
    if (!/^\d{4}-\d{2}-\d{2}$/.test(dirName)) continue;
    if (!Object.values(entry).every(isComplete)) continue;
    for (const [localDay, fields] of Object.entries(entry)) addFields(merged, localDay, fields);
  }

  if (dirty) {
    try {
      mkdirSync(dirname(DAILY_CACHE), { recursive: true, mode: 0o700 });
      writeFileSync(DAILY_CACHE, JSON.stringify(cache), { mode: 0o600 });
    } catch { /* cache is an optimisation; losing it costs a rescan */ }
  }

  // readUsageStats already scanned the exact records that make up local
  // today (same files, same fields), so its result replaces whatever this
  // pass computed for that date rather than being counted twice.
  if (todayOverride) {
    const { day, ...fields } = todayOverride;
    merged.set(day, fields);
  }

  return [...merged.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([day, fields]) => ({ day, ...fields }));
}

/** Lifetime figures for the stats screen, derived from every day of logs on
 * disk rather than today's slice. Uses the same per-day cache, so the cost is
 * one rescan of today and yesterday.
 *
 * Streaks count days with at least one call. A streak that ended yesterday is
 * still reported as current until today produces no calls by end of day, which
 * is why "current" is computed from the most recent active day rather than
 * requiring today specifically: penalising someone at 00:05 for not having
 * worked yet would be wrong. */
/** 1.6B / 42.5M / 116k. The exact digit never changes a decision. */
/** Input minus cache reads: the text actually sent fresh, as opposed to the
 * conversation history re-sent on every turn. Clamped because a malformed log
 * could otherwise produce a negative count; cacheRead is a subset of `in`
 * whenever the data is sane. */
export function netTokens(tokensIn: number, tokensCacheRead: number): number {
  return Math.max(0, tokensIn - tokensCacheRead);
}

export function compactNum(n: number): string {
  if (n >= 1_000_000_000) return `${(n / 1_000_000_000).toFixed(1)}B`;
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(1)}M`;
  if (n >= 1_000) return `${Math.round(n / 1_000)}k`;
  return String(n);
}

/** A human-scale comparison for a token count.
 *
 * Feed this DISTINCT tokens, not total input. Most input on a long session is
 * cache reads: the same conversation history re-sent on every turn. Counting
 * those as text read would say a paragraph re-read a thousand times is a
 * thousand paragraphs. On the machine this was written for, cache reads were
 * 81.5% of all input, so comparing against the raw total overstated by roughly
 * five times.
 *
 * Word counts are the published lengths of the works. The words-to-tokens
 * factor is an approximation for English prose, and code tokenizes denser than
 * prose, so the result still leans high; that is why every one carries a tilde.
 * It is a toy and it reads as one, but the arithmetic is real and the
 * denominator is the honest one.
 */
export function tokenComparison(tokens: number): string | undefined {
  if (tokens <= 0) return undefined;
  const WORDS_TO_TOKENS = 1.33;
  const WORKS: [string, number][] = [
    ["Animal Farm", 29_966],
    ["The Hobbit", 95_356],
    ["Pride and Prejudice", 122_189],
    ["The Lord of the Rings", 481_103],
    ["War and Peace", 587_287],
    ["the Harry Potter series", 1_084_170],
  ];
  // Prefer the work that yields a multiple a person can hold in their head:
  // the largest work still exceeded at least twice over.
  let best: [string, number] | undefined;
  for (const [title, words] of WORKS) {
    if (tokens / (words * WORDS_TO_TOKENS) >= 2) best = [title, words];
  }
  if (!best) return undefined;
  const times = Math.round(tokens / (best[1] * WORDS_TO_TOKENS));
  return `~${times.toLocaleString()}x the text of ${best[0]}`;
}

export async function readLifetimeStats(todayOverride?: DayTotal): Promise<LifetimeStats | undefined> {
  const days = await readDailyTokens(todayOverride);
  const active = days.filter((d) => d.calls > 0);
  if (active.length === 0) return undefined;

  const tokensIn = active.reduce((n, d) => n + d.tokensIn, 0);
  const tokensOut = active.reduce((n, d) => n + d.tokensOut, 0);
  const tokensCacheRead = active.reduce((n, d) => n + d.tokensCacheRead, 0);
  const tokensCacheWrite = active.reduce((n, d) => n + d.tokensCacheWrite, 0);
  const tokensReasoning = active.reduce((n, d) => n + d.tokensReasoning, 0);
  const calls = active.reduce((n, d) => n + d.calls, 0);

  const dayMs = 86_400_000;
  const asDate = (d: string): number => new Date(`${d}T00:00:00`).getTime();
  let longest = 0;
  let run = 0;
  let prev = 0;
  for (const d of active) {
    const t = asDate(d.day);
    run = prev && t - prev === dayMs ? run + 1 : 1;
    longest = Math.max(longest, run);
    prev = t;
  }
  // Current streak: walk back from the last active day while days stay adjacent.
  let current = 0;
  for (let i = active.length - 1; i >= 0; i--) {
    if (i === active.length - 1) { current = 1; continue; }
    if (asDate(active[i + 1].day) - asDate(active[i].day) === dayMs) current++;
    else break;
  }
  const today = new Date();
  const todayKey = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, "0")}-${String(today.getDate()).padStart(2, "0")}`;
  const last = active[active.length - 1].day;
  const gapDays = Math.round((asDate(todayKey) - asDate(last)) / dayMs);
  if (gapDays > 1) current = 0;

  return { tokensIn, tokensOut, tokensCacheRead, tokensCacheWrite, tokensReasoning, calls, activeDays: active.length, currentStreak: current, longestStreak: longest, days };
}

export async function readUsageStats(): Promise<UsageStats | undefined> {
  if (!CALL_LOGS) return undefined;
  const targetLocalDay = today();
  // The router names its directories by UTC calendar day; "today" is a LOCAL
  // calendar day, and the two boundaries disagree by the local UTC offset for
  // anyone not on UTC. Reading only the directory literally named today's
  // local date misses every record written before UTC midnight (a 7-hour
  // window at UTC+7, every single day) and, once that directory exists,
  // eventually the reverse for its own tail. Local today can only ever be fed
  // by the most recently created UTC directories, so the last two are read
  // and every record is kept or dropped by comparing ITS OWN timestamp's
  // local date against today — never by trusting either directory's name.
  let dirs: string[];
  try {
    dirs = (await readdir(CALL_LOGS)).filter((d) => /^\d{4}-\d{2}-\d{2}$/.test(d)).sort();
  } catch {
    return undefined;
  }
  const candidates = dirs.slice(-2);
  const files: { dir: string; name: string }[] = [];
  for (const d of candidates) {
    try {
      for (const name of await readdir(join(CALL_LOGS, d))) {
        if (name.endsWith(".json")) files.push({ dir: d, name });
      }
    } catch { /* directory not created yet, e.g. before UTC midnight — not an error */ }
  }
  if (files.length === 0) return undefined;

  const byModel = new Map<string, { calls: number; tokensIn: number; errors: number; durations: number[] }>();
  const byStatus = new Map<number, number>();
  const byHour = new Map<number, number>();
  let calls = 0;
  let errors = 0;
  let tokensIn = 0;
  let tokensOut = 0;
  let tokensCacheRead = 0;
  let tokensCacheWrite = 0;
  let tokensReasoning = 0;
  const durations: number[] = [];
  let partial = false;
  let lastHourCalls = 0;
  let lastHourTokensIn = 0;
  let slowest: { duration: number; model: string } | undefined;

  // Bounded concurrency: unbounded Promise.all over thousands of files spikes
  // file descriptors for no throughput gain.
  const BATCH = 64;
  for (let i = 0; i < files.length; i += BATCH) {
    const batch = files.slice(i, i + BATCH);
    const results = await Promise.all(batch.map(async (f) => {
      try {
        return JSON.parse(await readFile(join(CALL_LOGS, f.dir, f.name), "utf8")) as { summary?: Record<string, unknown> };
      } catch {
        return undefined;
      }
    }));
    for (const r of results) {
      const s = r?.summary;
      if (!s) {
        partial = true;
        continue;
      }
      // The whole point of reading two directories: keep only the records
      // that actually belong to local today, wherever they happen to sit.
      if (typeof s.timestamp !== "string" || s.timestamp.length < 10 || localDateOf(s.timestamp) !== targetLocalDay) continue;
      calls++;
      const status = typeof s.status === "number" ? s.status : 0;
      if (status >= 400) {
        errors++;
        byStatus.set(status, (byStatus.get(status) ?? 0) + 1);
      }
      const tk = s.tokens as Record<string, unknown> | undefined;
      const callIn = tk ? Number(tk.in) || 0 : 0;
      if (tk) {
        tokensIn += callIn;
        tokensOut += Number(tk.out) || 0;
        tokensCacheRead += Number(tk.cacheRead) || 0;
        tokensCacheWrite += Number(tk.cacheWrite) || 0;
        tokensReasoning += Number(tk.reasoning) || 0;
      }
      const dur = Number(s.duration);
      const model = shortModel(String(s.model ?? "unknown"));
      if (Number.isFinite(dur) && dur > 0) {
        durations.push(dur);
        if (!slowest || dur > slowest.duration) slowest = { duration: dur, model };
      }
      const m = byModel.get(model) ?? { calls: 0, tokensIn: 0, errors: 0, durations: [] };
      m.calls++;
      m.tokensIn += callIn;
      if (status >= 400) m.errors++;
      if (Number.isFinite(dur) && dur > 0) m.durations.push(dur);
      byModel.set(model, m);
      // Timestamps are ISO-8601 UTC. Slicing the hour out of the string buckets
      // by UTC, which put the busiest hour seven columns from where it happened
      // for anyone not on UTC, in a row that sits beside a local clock. Parse
      // and convert so the sparkline and the clock describe the same day.
      const ts = typeof s.timestamp === "string" ? s.timestamp : "";
      if (ts.length >= 13) {
        const t = new Date(ts);
        const h = t.getHours();
        if (Number.isFinite(h)) byHour.set(h, (byHour.get(h) ?? 0) + 1);
        if (Date.now() - t.getTime() <= 3_600_000) {
          lastHourCalls++;
          lastHourTokensIn += callIn;
        }
      }
    }
  }
  if (calls === 0) return undefined;

  const perModel = [...byModel.entries()]
    .sort((a, b) => b[1].calls - a[1].calls)
    .map(([model, m]) => {
      m.durations.sort((x, y) => x - y);
      const p95 = m.durations.length > 0
        ? m.durations[Math.min(m.durations.length - 1, Math.floor(m.durations.length * 0.95))]
        : 0;
      return { model, calls: m.calls, tokensIn: m.tokensIn, errors: m.errors, p95 };
    });
  const topModels = perModel
    .slice(0, 3)
    .map((m) => ({ model: m.model, pct: Math.round((m.calls / calls) * 100) }));
  const errorsByStatus = [...byStatus.entries()].sort((a, b) => b[1] - a[1]);

  const lastHour = byHour.size > 0 ? Math.max(...byHour.keys()) : 0;
  const hourly: number[] = [];
  for (let h = 0; h <= lastHour; h++) hourly.push(byHour.get(h) ?? 0);

  // Four coarse buckets. Finer slicing implies a precision that call counts at
  // this volume do not support.
  const PERIODS: [string, number[]][] = [
    ["morning", [5, 6, 7, 8, 9, 10, 11]],
    ["afternoon", [12, 13, 14, 15, 16]],
    ["evening", [17, 18, 19, 20, 21]],
    ["night", [22, 23, 0, 1, 2, 3, 4]],
  ];
  let peakPeriod: { label: string; pct: number } | undefined;
  if (calls >= 20) {
    const scored = PERIODS.map(([label, hrs]) => ({
      label,
      n: hrs.reduce((sum, h) => sum + (byHour.get(h) ?? 0), 0),
    })).sort((a, b) => b.n - a.n);
    if (scored[0].n > 0) peakPeriod = { label: scored[0].label, pct: Math.round((scored[0].n / calls) * 100) };
  }

  durations.sort((a, b) => a - b);
  return { calls, errors, tokensIn, tokensOut, tokensCacheRead, tokensCacheWrite, tokensReasoning, peakPeriod, durations, topModels, perModel, errorsByStatus, slowest, hourly, peakHour: Math.max(0, ...hourly), partial, lastHour: { calls: lastHourCalls, tokensIn: lastHourTokensIn } };
}

/**
 * Lazily-refreshed cache with a 60s TTL. Reads never block: callers get the
 * previous value (or undefined on first paint) and a refresh is kicked off in
 * the background, so the dashboard is navigable immediately on open.
 */
const STATS_TTL_MS = 60_000;

/** Days in the band's sparkline. A trailing week: seven bars map to the unit
 * people already think in, and the row has to share space with everything else
 * on it. */
const DAILY_WINDOW = 7;

export class StatsCache {
  private value: UsageStats | undefined;
  private daily: DayTotal[] = [];
  private life: LifetimeStats | undefined;
  private loaded = false;
  private fetchedAt = 0;
  private inFlight = false;

  constructor(private onUpdate: () => void) {}

  /** Lifetime figures for the stats screen. Same refresh cycle as the band. */
  lifetime(): LifetimeStats | undefined { return this.life; }

  /** Non-blocking. Triggers a background refresh when stale. Both figures come
   * from one pass so the band never mixes a fresh today with a stale history. */
  get(): { stats: UsageStats | undefined; daily: DayTotal[]; loaded: boolean } {
    if (!this.inFlight && Date.now() - this.fetchedAt > STATS_TTL_MS) {
      this.inFlight = true;
      // Sequential on purpose: readUsageStats scans today's directory for the
      // band, and its totals are handed to readLifetimeStats so the lifetime
      // walk skips that directory rather than scanning it a second time in
      // the same refresh. Both count identically — same files, same summary
      // fields — so the substitution cannot change a number.
      readUsageStats()
        .then(async (s) => {
          const override: DayTotal | undefined = s
            ? { day: today(), tokensIn: s.tokensIn, tokensOut: s.tokensOut, tokensCacheRead: s.tokensCacheRead, tokensCacheWrite: s.tokensCacheWrite, tokensReasoning: s.tokensReasoning, calls: s.calls }
            : undefined;
          const l = await readLifetimeStats(override);
          this.value = s; this.life = l; this.daily = l ? l.days.slice(-DAILY_WINDOW) : [];
        })
        .catch(() => { this.value = undefined; this.daily = []; this.life = undefined; })
        .finally(() => {
          this.loaded = true;
          this.fetchedAt = Date.now();
          this.inFlight = false;
          this.onUpdate();
        });
    }
    return { stats: this.value, daily: this.daily, loaded: this.loaded };
  }
}

